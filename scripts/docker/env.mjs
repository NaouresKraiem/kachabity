// Writes .env.docker for the local Docker setup (docs/DOCKER.md) from the running local Supabase.
// Usage: node scripts/docker/env.mjs   (after `npx supabase start`; keeps an existing file)
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';

const FILE = '.env.docker';
if (existsSync(FILE)) {
    console.log(`${FILE} already exists; delete it to regenerate.`);
    process.exit(0);
}

const status = JSON.parse(execSync('npx -y supabase@2.121.0 status -o json', { encoding: 'utf8' }));
// The browser and the web container (through the compose gateway) use localhost; the api
// container reaches the host's Supabase through host.docker.internal.
const browserUrl = 'http://localhost:54321';
const containerUrl = 'http://host.docker.internal:54321';

writeFileSync(
    FILE,
    `# Local Docker setup only (docs/DOCKER.md). Generated by scripts/docker/env.mjs; never put live keys here.
ENV=local
NEXT_PUBLIC_SITE_URL=http://localhost:3000
NEXT_PUBLIC_SUPABASE_URL=${browserUrl}
NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}
SUPABASE_SERVICE_ROLE_KEY=${status.SERVICE_ROLE_KEY}
SUPABASE_URL=${containerUrl}
# Signs session cookies (NestJS auth API); the web container needs the same value.
AUTH_SECRET=${randomBytes(32).toString('base64url')}
DATABASE_URL=postgresql://postgres:postgres@host.docker.internal:54322/postgres
# Comma-separated e-mails that get the owner role (sign in with the same password as on the live site
# after importing live data).
OWNER_EMAILS=
ADMIN_EMAILS=
# API areas served by NestJS (rebuild web after changing: docker compose up --build).
NEST_ROUTES=categories,upload/image,finance/documents
NEST_URL=http://localhost:4000
REVALIDATE_SECRET=${crypto.randomUUID()}
# File storage: the local S3-compatible storage in docker-compose.yml (Cloudflare R2 in production).
S3_ENDPOINT=http://localhost:9000
S3_ACCESS_KEY_ID=kachabity-local
S3_SECRET_ACCESS_KEY=kachabity-local-secret
FILES_PUBLIC_URL=http://localhost:9000/products
# scripts/docker/import-live-data.mjs reads the live project (read only). By default it uses the REST
# API with the URL and service-role key from .env.local, and every account gets LOCAL_PASSWORD.
# With the database password, set SOURCE_DATABASE_URL (Connect → Session pooler, postgresql://...)
# to use pg_dump instead and keep the live passwords.
SOURCE_DATABASE_URL=
LOCAL_PASSWORD=Kachabity-local-1
`
);
console.log(`Wrote ${FILE}.`);
